"""Instruction generator for A2A V2 open-instruction system.

Supports two modes:
  1. JSON mode: Load pre-generated instructions from a JSON file (preferred)
  2. Template mode: Fallback template + descriptor combination

The JSON file is generated by scripts/generate_instructions.py using an LLM.
"""

import json
import os
import random


class InstructionGenerator:
    """Generates diverse natural language instructions for cross-modal translation."""

    def __init__(self, instructions_path: str = None):
        self.json_instructions = {}
        self.use_json = False

        # Try to load JSON instructions
        if instructions_path and os.path.exists(instructions_path):
            with open(instructions_path, "r", encoding="utf-8") as f:
                self.json_instructions = json.load(f)
            total = sum(len(v) for v in self.json_instructions.values())
            if total > 0:
                self.use_json = True
                print(f"Loaded {total} pre-generated instructions from {instructions_path}")
                for key, instrs in self.json_instructions.items():
                    print(f"  {key}: {len(instrs)} instructions")

        # Template fallback (always available)
        self._init_templates()

    def _init_templates(self):
        """Initialize template-based instruction components."""
        self.descriptors = {
            "rgb": {
                "visual": ["photorealistic aerial view", "true-color visible-spectrum image",
                           "vibrant color photograph"],
                "resolution": ["0.2m high-resolution", "sub-meter sharp", "very-high-resolution"],
                "sensor": ["aerial orthophoto", "airborne camera capture", "overhead visual survey"],
            },
            "nir": {
                "visual": ["grayscale infrared intensity map", "monochromatic near-infrared image",
                           "uniform grey-scale infrared"],
                "physical": ["chlorophyll reflectance", "vegetation response", "near-infrared luminance"],
                "sensor": ["single-band infrared capture", "infrared aerial sensor", "NIR channel extraction"],
            },
            "dem": {
                "visual": ["colorless structural elevation map", "three-layer topographic tensor",
                           "geometric height representation"],
                "physical": ["DSM, DTM, and object height", "surface and terrain elevation",
                             "physical height in meters"],
                "sensor": ["photogrammetry-derived elevation", "dense-matching 3D model",
                           "digital surface and terrain model"],
            },
            "spot": {
                "visual": ["slightly blurred satellite view", "coarser orbital observation",
                           "muted spectral image"],
                "physical": ["1.6m orbital reflectance", "spaceborne multispectral",
                             "satellite bottom-of-atmosphere"],
                "sensor": ["SPOT 6-7 satellite capture", "orbital sensor imagery",
                           "macroscopic satellite view"],
            },
        }
        self.verbs = {
            "rgb": ["restore", "synthesize", "reconstruct", "render", "generate"],
            "nir": ["extract", "compute", "render", "produce", "reveal"],
            "dem": ["derive", "compute", "generate", "produce", "abstract"],
            "spot": ["simulate", "render", "generate", "produce", "synthesize"],
        }
        self.templates = [
            "Convert the {src} into a {tgt}.",
            "Transform this {src} to produce a {tgt}.",
            "Translate the {src} into {tgt}.",
            "{verb_cap} a {tgt} from the {src}.",
            "From this {src}, {verb} a {tgt}.",
            "Given a {src}, {verb} the corresponding {tgt}.",
            "Starting from the {src}, {verb} a {tgt}.",
        ]

    def generate(self, src_modality: str, tgt_modality: str) -> str:
        """Generate a random instruction for src→tgt translation."""
        if self.use_json:
            return self._generate_from_json(src_modality, tgt_modality)
        return self._generate_from_template(src_modality, tgt_modality)

    def _generate_from_json(self, src_modality: str, tgt_modality: str) -> str:
        """Sample from pre-generated JSON instructions."""
        key = f"{src_modality}_to_{tgt_modality}"
        pool = self.json_instructions.get(key, [])

        if not pool:
            return self._generate_from_template(src_modality, tgt_modality)

        item = random.choice(pool)
        if isinstance(item, dict):
            return item["instruction"]
        return str(item)

    def get_stats(self) -> dict:
        """Return statistics about loaded instructions."""
        if not self.use_json:
            return {"mode": "template", "total": 0}
        stats = {"mode": "json", "pairs": {}}
        total = 0
        for key, instrs in self.json_instructions.items():
            categories = {}
            for inst in instrs:
                cat = inst.get("category", "unknown") if isinstance(inst, dict) else "unknown"
                categories[cat] = categories.get(cat, 0) + 1
            stats["pairs"][key] = {"count": len(instrs), "categories": categories}
            total += len(instrs)
        stats["total"] = total
        return stats

    def _generate_from_template(self, src_modality: str, tgt_modality: str) -> str:
        """Fallback: template-based instruction generation."""
        src_desc = self._sample_descriptor(src_modality)
        tgt_desc = self._sample_descriptor(tgt_modality)
        verb = random.choice(self.verbs[tgt_modality])
        template = random.choice(self.templates)
        return template.format(src=src_desc, tgt=tgt_desc, verb=verb, verb_cap=verb.capitalize())

    def _sample_descriptor(self, modality: str) -> str:
        d = self.descriptors[modality]
        categories = random.sample(list(d.keys()), k=random.randint(1, 2))
        return " ".join(random.choice(d[cat]) for cat in categories)